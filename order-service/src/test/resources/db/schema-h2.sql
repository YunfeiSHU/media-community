-- order-service 测试用建表脚本（H2，MODE=MySQL）
-- 由 src/test/resources/application-test.yml 的 spring.sql.init.schema-locations 自动执行
-- 与 db/schema.sql 语义等价：仅把 AUTO_INCREMENT 换成 IDENTITY、内联索引换成 CREATE INDEX
-- ============================================================

CREATE TABLE IF NOT EXISTS `order` (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id VARCHAR(32) NOT NULL,
    uid VARCHAR(32) NOT NULL,
    status TINYINT NOT NULL DEFAULT 0,
    total_amount BIGINT NOT NULL,
    expire_at DATETIME NULL,
    paid_at DATETIME NULL,
    completed_at DATETIME NULL,
    cancelled_at DATETIME NULL,
    created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE UNIQUE INDEX IF NOT EXISTS uk_order_id ON `order` (order_id);
CREATE INDEX IF NOT EXISTS idx_uid_created_at ON `order` (uid, created_at);
CREATE INDEX IF NOT EXISTS idx_status_expire_at ON `order` (status, expire_at);

CREATE TABLE IF NOT EXISTS `order_item` (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id BIGINT NOT NULL,
    product_id VARCHAR(32) NOT NULL,
    sku_id VARCHAR(32) NOT NULL,
    product_name VARCHAR(128) NOT NULL,
    sku_name VARCHAR(128) NOT NULL,
    unit_price BIGINT NOT NULL,
    quantity INT NOT NULL,
    total_amount BIGINT NOT NULL,
    created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX IF NOT EXISTS idx_order_id ON `order_item` (order_id);
CREATE INDEX IF NOT EXISTS idx_product_id ON `order_item` (product_id);
CREATE INDEX IF NOT EXISTS idx_sku_id ON `order_item` (sku_id);

CREATE TABLE IF NOT EXISTS `payment_order` (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    payment_id VARCHAR(32) NOT NULL,
    order_id VARCHAR(32) NOT NULL,
    uid VARCHAR(32) NOT NULL,
    amount BIGINT NOT NULL,
    status TINYINT NOT NULL DEFAULT 0,
    payment_channel TINYINT NOT NULL,
    transaction_id VARCHAR(128) NULL,
    expire_at DATETIME NULL,
    paid_at DATETIME NULL,
    created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE UNIQUE INDEX IF NOT EXISTS uk_payment_id ON `payment_order` (payment_id);
CREATE UNIQUE INDEX IF NOT EXISTS uk_transaction_id ON `payment_order` (transaction_id);
CREATE INDEX IF NOT EXISTS idx_payment_order_order_id ON `payment_order` (order_id);
CREATE INDEX IF NOT EXISTS idx_payment_uid_created_at ON `payment_order` (uid, created_at);

CREATE TABLE IF NOT EXISTS `payment_record` (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    payment_id VARCHAR(32) NOT NULL,
    transaction_id VARCHAR(128) NULL,
    payment_channel TINYINT NOT NULL,
    callback_status TINYINT NOT NULL,
    callback_data TEXT NULL,
    created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX IF NOT EXISTS idx_payment_id ON `payment_record` (payment_id);
CREATE INDEX IF NOT EXISTS idx_record_transaction_id ON `payment_record` (transaction_id);
